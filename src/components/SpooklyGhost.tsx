const IDLE_MS = 3000
const ACTIVITY = ['pointermove', 'pointerdown', 'keydown', 'scroll'] as const

export function SpooklyGhost({ className = '' }: { className?: string }) {
  const [blink, setBlink] = useState({ count: 0, twice: false })

  useEffect(() => {
    let lastActive = Date.now()
    const wake = () => { lastActive = Date.now() }
    let timer: ReturnType<typeof setTimeout>
    const tick = () => {
      if (Date.now() - lastActive >= IDLE_MS && document.visibilityState === 'visible')
        setBlink(b => ({ count: b.count + 1, twice: Math.random() < 0.3 }))
      timer = setTimeout(tick, 2200 + Math.random() * 2600)
    }
    for (const type of ACTIVITY) window.addEventListener(type, wake, { passive: true })
    timer = setTimeout(tick, IDLE_MS)
    return () => {
      clearTimeout(timer)
      for (const type of ACTIVITY) window.removeEventListener(type, wake)
    }
  }, [])

  return (
    <svg
      aria-hidden
      viewBox="292 153 709 950"
      className={`ghost ${className}`}
      style={{ fill: 'var(--ink)' }}
    >
      <path d={BODY} />
      <g
        key={blink.count}
        className={
          blink.count === 0
            ? undefined
            : blink.twice
              ? 'ghost-blink-twice'
              : 'ghost-blink'
        }
      >
        {EYES.map(d => (
          <path key={d} d={d} style={{ fill: 'var(--bg)' }} className="ghost-eye" />
        ))}
      </g>
    </svg>
  )
}
